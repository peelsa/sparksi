"""Fallback that runs a catalog start script. Env is only PORT and HOST.

Image-tool rows keep their existing scripts. Two-Spark model templates do not
use this builder; those are generated by the engine modules.
"""

from __future__ import annotations

from sparksi.recipes.engines.common import launch_for
from sparksi.recipes.spec import Built, Spec


def build(spec: Spec) -> Built:
    role = "head" if spec.placement == "both" else ("worker" if spec.placement == "worker" else "head")
    host = spec.hosts.get(role) or ""
    scripts = spec.scripts.get(host) or spec.scripts.get(role) or {}
    if spec.placement == "both" and not scripts:
        scripts = spec.scripts.get(spec.hosts.get("head") or "") or {}
    start = list(scripts.get("start") or [])
    stop = list(scripts.get("stop") or [])
    if not start:
        raise ValueError("no start script for this model")
    env = {"PORT": str(int(spec.port)), "HOST": spec.binds.get(role) or ""}
    node = launch_for(spec, role, start, env, container="", stop=stop)
    order = [role]
    return Built(nodes=[node], order=order, experimental=False, health_paths=["/health"])
